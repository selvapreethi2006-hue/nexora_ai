import { Conversation, AppSettings, ChatMessage } from '../types/chat';

const STORAGE_KEY_CONVERSATIONS = 'nexora_conversations_v1';
const STORAGE_KEY_ACTIVE_ID = 'nexora_active_conversation_id_v1';
const STORAGE_KEY_SETTINGS = 'nexora_app_settings_v1';

export const DEFAULT_SETTINGS: AppSettings = {
  theme: 'dark',
  preferredLanguage: 'auto',
  responseStyle: 'balanced',
  enableWebSearch: false,
  ttsVoice: 'Kore',
  fontSize: 'md',
  autoScroll: true,
};

export function loadSettings(): AppSettings {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_SETTINGS);
    if (!raw) return DEFAULT_SETTINGS;
    return { ...DEFAULT_SETTINGS, ...JSON.parse(raw) };
  } catch (e) {
    console.error('Failed to load settings:', e);
    return DEFAULT_SETTINGS;
  }
}

export function saveSettings(settings: AppSettings): void {
  try {
    localStorage.setItem(STORAGE_KEY_SETTINGS, JSON.stringify(settings));
  } catch (e) {
    console.error('Failed to save settings:', e);
  }
}

export function loadConversations(): Conversation[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_CONVERSATIONS);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch (e) {
    console.error('Failed to load conversations:', e);
    return [];
  }
}

export function saveConversations(conversations: Conversation[]): void {
  try {
    localStorage.setItem(STORAGE_KEY_CONVERSATIONS, JSON.stringify(conversations));
  } catch (e) {
    console.error('Failed to save conversations:', e);
  }
}

export function loadActiveConversationId(): string | null {
  try {
    return localStorage.getItem(STORAGE_KEY_ACTIVE_ID);
  } catch {
    return null;
  }
}

export function saveActiveConversationId(id: string | null): void {
  try {
    if (id) {
      localStorage.setItem(STORAGE_KEY_ACTIVE_ID, id);
    } else {
      localStorage.removeItem(STORAGE_KEY_ACTIVE_ID);
    }
  } catch (e) {
    console.error('Failed to save active conversation id:', e);
  }
}

export function generateChatTitle(firstMessageText: string): string {
  const cleaned = firstMessageText.trim().replace(/^["']|["']$/g, '');
  if (!cleaned) return 'New Conversation';
  const firstLine = cleaned.split('\n')[0];
  if (firstLine.length <= 40) return firstLine;
  return firstLine.substring(0, 37) + '...';
}

export function exportChatAsMarkdown(conversation: Conversation): string {
  let md = `# ${conversation.title}\n`;
  md += `*Generated by Nexora AI on ${new Date(conversation.createdAt).toLocaleString()}*\n\n---\n\n`;

  for (const msg of conversation.messages) {
    const sender = msg.role === 'user' ? 'User' : 'Nexora AI';
    const time = new Date(msg.timestamp).toLocaleTimeString();
    md += `### ${sender} (${time})\n\n${msg.content}\n\n`;

    if (msg.sources && msg.sources.length > 0) {
      md += `**Sources:**\n`;
      msg.sources.forEach((s) => {
        md += `- [${s.title}](${s.uri})\n`;
      });
      md += '\n';
    }
    md += `---\n\n`;
  }

  return md;
}

export function exportChatAsJSON(conversation: Conversation): string {
  return JSON.stringify(conversation, null, 2);
}

export function clearAllConversations(): void {
  try {
    localStorage.removeItem(STORAGE_KEY_CONVERSATIONS);
    localStorage.removeItem(STORAGE_KEY_ACTIVE_ID);
  } catch (e) {
    console.error('Failed to clear conversations:', e);
  }
}
